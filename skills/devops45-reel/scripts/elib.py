"""Shared helpers for the devops45-reel scripts. Every script takes the PROJECT dir (…/output/<episode_id>/project).

Layout of an episode:
  <out>/                       deliverables (final.mp4, cover.jpg, captions.srt, caption.txt, alt_text.txt, report.json, stems)
  <out>/project/episode.json   what the producer wrote from the brief (scenes → archetypes)  ← THE input
  <out>/project/brief.json     the Showrunner brief as received (kept for QA)
  <out>/project/audio/voice/   take.mp3 (ElevenLabs) + take.words.json (Whisper)
  <out>/project/plan/          voice.json, music.json, scenes.json
  <out>/project/video/         Remotion project (template copy; node_modules hard-linked)
"""
import json
import os
import re
import sys
import unicodedata

SKILL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS, SR = 60, 48000


def proj(argv=None):
    a = (argv or sys.argv)[1:]
    if not a:
        sys.exit("usage: <script> <project dir>  (…/reels/output/<episode_id>/project)")
    p = os.path.abspath(os.path.expanduser(a[0]))
    if not os.path.exists(f"{p}/episode.json") and os.path.exists(f"{p}/project/episode.json"):
        p = f"{p}/project"
    return p


def out_dir(p):
    return os.path.dirname(p)


def load_episode(p):
    return json.load(open(f"{p}/episode.json", encoding="utf-8"))


def norm(s):
    """lowercase, no accents, letters/digits only (for matching Whisper tokens to the script)"""
    s = unicodedata.normalize("NFD", s.lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return re.sub(r"[^a-z0-9]+", "", s)


def tokens(text):
    """script text → normalized word tokens (« l'IA » → l, ia; « 45 » → 45; « -tulpn » → tulpn)"""
    return [t for t in (norm(w) for w in re.split(r"[\s'’\-/:.,;!?…«»()\"]+", text)) if t]


SENT = re.compile(r"(?<=[.?!…])\s+")


def sentences(text):
    """split a scene's `say` into phrases (one per sentence). Keeps punctuation."""
    text = re.sub(r"\s+", " ", text.strip())
    return [s.strip() for s in SENT.split(text) if s.strip()]


def phrases(ep):
    """[(phrase_id, scene_id, text)] in order, from episode.json scenes[].say"""
    out, n = [], 0
    for sc in ep["scenes"]:
        for s in sentences(sc.get("say", "")):
            n += 1
            out.append((f"p{n:02d}", sc["id"], s))
    return out


def clean_script(ep):
    return " ".join(sc.get("say", "").strip() for sc in ep["scenes"] if sc.get("say", "").strip())


def wjson(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=1)


def ts_header(script):
    return f"// GENERATED by devops45-reel/scripts/{script} — do not edit by hand. Frames are GLOBAL (60 fps).\n"


def audio16k(path):
    """mono float32 16 kHz array via ffmpeg (faster-whisper's own decoder breaks with this venv's PyAV)"""
    import subprocess

    import numpy as np
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", "16000", "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()
