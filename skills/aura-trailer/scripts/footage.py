"""Cut the shot library from footage.json into video/public/footage/ and write video/src/data/footage.ts + a contact sheet.
Every clip: H.264 CRF 16, muted (the mixer owns all sound), 30 fps unless the clip says "fps": 60.

footage.json:
  {"presets": {"full": "scale=1080:1920:flags=lanczos,setsar=1", "<name>": "<ffmpeg -vf chain>"},
   "clips": [{"id": "said", "kind": "master", "src": "source/XYZ.mp4", "start": 0, "dur": 59.9, "vf": "full",
              "desc": "what is in it (agents pick shots from this)", "matte": "path/to/cutout.webm", "sheet_t": 20}]}
kind: master (a lip-sync source: cut from second 0 of the file whose audio gives the voice lines), face, screen,
      episode, card (a lip-sync crop), reel ... free text, agents read it.
Existing clips are kept (delete video/public/footage/<id>.mp4 to re-cut one).
Run in the project folder: python3 ~/.claude/skills/aura-trailer/scripts/footage.py
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tlib  # noqa: E402

FJ = json.load(open(tlib.path("footage.json"), encoding="utf-8"))
PRESETS = {"full": "scale=1080:1920:flags=lanczos,setsar=1", **FJ.get("presets", {})}
OUT = tlib.path("video/public/footage")
os.makedirs(OUT, exist_ok=True)

meta = []
for c in FJ["clips"]:
    cid, src = c["id"], tlib.path(c["src"])
    vf = PRESETS.get(c.get("vf", "full"), c.get("vf", "full"))
    fps = int(c.get("fps", 30))
    out = f"{OUT}/{cid}.mp4"
    if not os.path.exists(out):
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-ss", str(c.get("start", 0)), "-i", src, "-t", str(c["dur"]),
                        "-vf", vf + f",fps={fps}", "-an", "-c:v", "libx264", "-preset", "medium", "-crf", "16",
                        "-pix_fmt", "yuv420p", "-movflags", "+faststart", out], check=True)
    wh = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height",
                         "-of", "csv=p=0", out], capture_output=True, text=True).stdout.strip().split(",")
    matte = ""
    if c.get("matte"):
        matte = f"footage/{cid}-matte.webm"
        if not os.path.exists(f"{OUT}/{cid}-matte.webm"):
            shutil.copy(tlib.path(c["matte"]), f"{OUT}/{cid}-matte.webm")
    meta.append({"id": cid, "kind": c.get("kind", ""), "src": f"footage/{cid}.mp4", "w": int(wh[0]), "h": int(wh[1]),
                 "seconds": c["dur"], "fps": fps, "sourceFile": os.path.basename(src), "sourceStart": c.get("start", 0),
                 "desc": c.get("desc", ""), "matte": matte})
    print(cid, wh, c.get("desc", "")[:60])

master = next((m for m in meta if m["kind"] == "master"), meta[0] if meta else None)
D = tlib.path("video/src/data")
os.makedirs(D, exist_ok=True)
with open(f"{D}/footage.ts", "w") as fh:
    fh.write("// GENERATED by aura-trailer/scripts/footage.py from footage.json — the shot library (all clips muted; staticFile(src)).\n")
    fh.write("export type Clip = {id: string; kind: string; src: string; w: number; h: number; seconds: number; fps: number; sourceFile: string; sourceStart: number; desc: string; matte: string};\n")
    fh.write(f"export const CLIPS: Clip[] = {json.dumps(meta, ensure_ascii=False, indent=1)};\n")
    fh.write("export const clip = (id: string) => CLIPS.find((c) => c.id === id)!;\n")
    fh.write("/** the main lip-sync master and its alpha cut-out (text behind the subject) */\n")
    mv = {"id": master["id"], "video": master["src"], "matte": master["matte"]} if master else {"id": "", "video": "", "matte": ""}
    fh.write(f"export const MASTER = {json.dumps(mv)};\n")

# contact sheet: one frame of every clip (agents and the director pick shots from it)
TW, TH, cols = 180, 320, 10
rows = (len(meta) + cols - 1) // cols
sheet = Image.new("RGB", (cols * TW, max(1, rows) * (TH + 16)), (12, 12, 12))
dr = ImageDraw.Draw(sheet)
tmp = os.path.join(tempfile.mkdtemp(), "ft.png")
for i, (c, m) in enumerate(zip(FJ["clips"], meta)):
    t = c.get("sheet_t", m["seconds"] / 2)
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-ss", str(t), "-i", f"{OUT}/{m['id']}.mp4", "-frames:v", "1",
                    "-vf", f"scale={TW}:{TH}:force_original_aspect_ratio=decrease,pad={TW}:{TH}:(ow-iw)/2:(oh-ih)/2", tmp], check=True)
    x, y = (i % cols) * TW, (i // cols) * (TH + 16)
    sheet.paste(Image.open(tmp), (x, y + 16))
    dr.text((x + 3, y + 2), m["id"], fill=(255, 255, 0))
os.makedirs(tlib.path("qa"), exist_ok=True)
sheet.save(tlib.path("qa/footage-sheet.jpg"), quality=85)
print("sheet", tlib.path("qa/footage-sheet.jpg"))
